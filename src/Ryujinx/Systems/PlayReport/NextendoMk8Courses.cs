    /// <summary>
    /// [Nextendo] Nom de dossier interne d'un circuit de Mario Kart 8 Deluxe -> nom affiche.
    ///
    /// FICHIER ENGENDRE. Ne pas le modifier a la main : le regenerer avec
    /// scratchpad/mk8/genere_circuits.py puis genere_cs.py.
    ///
    /// Le rapport de fin de course nomme le circuit sous sa forme interne (« Gu_FirstCircuit »).
    /// Les 107 correspondances ci-dessous viennent TOUTES du dump du joueur, par trois voies :
    ///
    ///  - le nom JAPONAIS du jeu, car les noms internes sont du japonais romanise
    ///    (パックンスライダー = G3ds_PackunSlider = Piranha Plant Pipeway) — cela couvre les
    ///    retro et les extensions, y compris ceux dont le nom anglais n'a aucun rapport ;
    ///  - les OBJETS poses sur le circuit, pour les trois que ni l'anglais ni le japonais ne
    ///    departagent : Gu_City porte CityBoat et Seagull (Toad Harbour), Gu_Ocean porte
    ///    meduses, bancs de poissons et courants (Dolphin Shoals), Gu_Expert porte ExTram,
    ///    le wagonnet de mine (Shy Guy Falls) ;
    ///  - la STRUCTURE pour les 48 du Booster Course Pass : leurs noms forment exactement la
    ///    grille Cnsw_AB (A de 1 a 6, B de 1 a 8), donc 11700 + (A-1)*8 + B est l'unique
    ///    bijection vers les 48 libelles consecutifs 11701..11748.
    ///
    /// Un garde-fou du generateur verifie que la table recouvre EXACTEMENT la liste des
    /// circuits jouables du binaire du jeu : ni manque, ni entree inconnue.
    ///
    /// Les langues absentes ci-dessous retombent sur l'anglais : Mario Kart 8 Deluxe n'est
    /// traduit qu'en 11 langues, l'emulateur en compte davantage.
    /// </summary>
    internal static class NextendoMk8Courses
    {
        /// <summary>Rend le nom affiche dans la langue de l'emulateur, ou une chaine vide.</summary>
        public static string NomAffiche(string nomInterne)
        {
            if (string.IsNullOrEmpty(nomInterne))
            {
                return "";
            }

            Dictionary<string, string> langue = ParLangue(LocaleManager.Instance.CurrentLanguageCode);

            if (langue.TryGetValue(nomInterne, out string nom))
            {
                return nom;
            }

            // Repli sur l'anglais : mieux vaut « Rainbow Road » que rien du tout.
            return _en_US.GetValueOrDefault(nomInterne, "");
        }

        /// <summary>Vrai si la table est renseignee. Sert au diagnostic, pas a l'affichage.</summary>
        public static bool EstRenseignee => _en_US.Count > 0;

